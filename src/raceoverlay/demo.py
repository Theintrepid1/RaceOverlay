"""Generate synthetic telemetry + a test clip so the pipeline can be demoed
without a real recording."""
from __future__ import annotations

import math
import subprocess


def write_demo_csv(path: str, seconds: float = 12.0, rate_hz: float = 20.0):
    """A TrackAddict-style CSV: '#' preamble, then a lap around a loop."""
    n = int(seconds * rate_hz)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# RaceRender Data (synthetic demo)\n")
        fh.write("# Generated by raceoverlay demo\n")
        fh.write("Time,Lap,Speed (MPH),Throttle Position (%),Brake,"
                 "Lateral G,Longitudinal G\n")
        for i in range(n):
            t = i / rate_hz
            phase = t / seconds * 2 * math.pi
            speed = 70 + 45 * math.sin(phase) ** 2            # 70..115 mph
            braking = max(0.0, -math.cos(phase))              # brake into corners
            throttle = max(0.0, math.cos(phase)) * 100.0
            brake = braking * 100.0
            lat_g = 1.3 * math.sin(phase * 2)
            lon_g = (throttle / 100.0) * 0.6 - braking * 1.1
            fh.write(f"{t:.3f},1,{speed:.2f},{throttle:.1f},{brake:.1f},"
                     f"{lat_g:.3f},{lon_g:.3f}\n")
    return path


def write_demo_video(path: str, seconds: float = 12.0, size: str = "1280x720",
                     fps: int = 30):
    """A moving test pattern that stands in for race footage."""
    subprocess.run(
        ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
         "-f", "lavfi", "-i",
         f"testsrc=size={size}:rate={fps},format=yuv420p",
         "-t", str(seconds), "-c:v", "libx264", "-crf", "20", path],
        check=True)
    return path
